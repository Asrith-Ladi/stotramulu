const fs = require('node:fs');
const assert = require('node:assert/strict');
const html = fs.readFileSync('public/index.html','utf8');
const js = fs.readFileSync('public/assets/japamala.js','utf8');
const modes = [...html.matchAll(/class="jm-mode-btn" data-mode="([^"]+)"/g)].map(match => match[1]);
assert.deepEqual(modes, ['flow','strand','full','rudraksha3d']);
for (const id of ['jmStageStrand','jmStageFull','jmStageFlow']) assert.ok(html.includes('id="'+id+'"'));
assert.doesNotMatch(html, /japamala-hand|jmStageHand/);
assert.doesNotMatch(js, /jmHand/);
assert.match(js, /includes\(mode\) \? mode : 'flow'/, 'removed saved modes fall back to Flow');
const renderer=fs.readFileSync('public/assets/japamala-3d.js','utf8');
assert.equal((renderer.match(/uniform mediump float uSeed;/g)||[]).length,2,'shared shader uniform precision matches');
assert.equal((renderer.match(/varying mediump vec3 vNormal;/g)||[]).length,2,'shared varying precision matches');
assert.ok(html.indexOf('assets/japamala-3d.js') < html.indexOf('assets/japamala.js'));
console.log('PASS: four mala modes, matching shader precision, Hand preference falls back to Flow.');
