const fs = require('node:fs');
const assert = require('node:assert/strict');
const html = fs.readFileSync('public/index.html','utf8');
const js = fs.readFileSync('public/assets/japamala.js','utf8');
const modes = [...html.matchAll(/class="jm-mode-btn" data-mode="([^"]+)"/g)].map(match => match[1]);
assert.deepEqual(modes, ['flow','strand','full']);
for (const id of ['jmStageStrand','jmStageFull','jmStageFlow']) assert.ok(html.includes('id="'+id+'"'));
assert.doesNotMatch(html, /japamala-3d|japamala-hand|3D graphics are unavailable|jmStageHand/);
assert.doesNotMatch(js, /Japamala3D|jmHand|rudraksha3d/);
assert.match(js, /includes\(mode\) \? mode : 'flow'/, 'removed saved modes fall back to Flow');
console.log('PASS: three supported mala modes; removed modes fall back to Flow.');
